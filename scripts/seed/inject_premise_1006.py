async def main():
    from app.core.redis_client import SessionManager
    from app.models.character import Character
    from app.models.outline import Outline
    from app.models.entity import Entity, EntityRelationship
    from app.core.database import get_session

    # 1) 更新 workflow_state（Redis）：引擎读写的是 workflow_{novel_id} 键
    #    注意：只允许写入 WorkflowState 的 dataclass 字段，未知字段会让 from_dict 崩溃
    from app.core.redis_client import SessionManager
    key = f"workflow_{NOVEL_ID}"
    state = await SessionManager.get_state(key)
    if not state:
        print("未找到 workflow_{} 状态".format(NOVEL_ID))
    else:
        state["world_setting"] = WORLD_SETTING
        state["characters"] = CHARACTERS
        state["plot_setting"] = PLOT_SETTING
        state["outline"] = OUTLINE
        state["chapter_outlines"] = CHAPTER_OUTLINES
        state["target_chapters"] = 100
        # 移除 legacy API 层写入、但 WorkflowState 不认识的键，避免 from_dict 崩溃
        for _k in ("waiting_for_user", "progress", "can_proceed", "messages", "current_state", "novel_id_legacy"):
            state.pop(_k, None)
        await SessionManager.save_state(key, state)
        print(f"[1] workflow_{NOVEL_ID} 已注入: 世界/角色/剧情/大纲/100章细纲")
    # 兼容旧 key（仅 API 层使用，不影响引擎）
    old_key = f"novel_{NOVEL_ID}"
    old = await SessionManager.get_state(old_key)
    if old:
        old["world_setting"] = WORLD_SETTING
        old["characters"] = CHARACTERS
        old["chapter_outlines"] = CHAPTER_OUTLINES
        await SessionManager.save_state(old_key, old)

    # 2) 清空并替换 characters 表
    async with get_session() as db:
        from app.models.character import RoleType
        from app.models.novel import Novel, Base
        from sqlalchemy import delete, select
        await db.execute(delete(Character).where(Character.novel_id == NOVEL_ID))
        await db.execute(delete(Outline).where(Outline.novel_id == NOVEL_ID))
        await db.execute(delete(Entity).where(Entity.novel_id == NOVEL_ID))
        await db.execute(delete(EntityRelationship).where(EntityRelationship.novel_id == NOVEL_ID))
        for c in CHARACTERS:
            db.add(Character(
                novel_id=NOVEL_ID, name=c["name"],
                role_type=RoleType(c["role_type"]),
                profile=c["profile"],
                first_appearance=1,
            ))
        # 卷大纲
        for v in OUTLINE["volumes"]:
            db.add(Outline(
                novel_id=NOVEL_ID, volume_number=v["volume"],
                volume_title=v["title"], arcs=v["arcs"], outline_type="main",
                target_chapters=10, actual_chapters=10,
                summary=v["title"],
            ))
        await db.commit()
        print("[2] 数据库已重置并写入 人物(%d)/大纲(%d卷)" % (len(CHARACTERS), len(OUTLINE["volumes"])))

    # 3) 同步实体（供图谱/地图/知识库）
    from app.services.workflow_entity_sync import WorkflowEntitySyncService
    sync = WorkflowEntitySyncService(NOVEL_ID)
    c = await sync.sync_characters(CHARACTERS)
    e = await sync.sync_world_setting(WORLD_SETTING)
    print(f"[3] 实体同步完成: 角色实体 {c} 个, 世界观实体 {e} 个")

    print("\n注入完成。可打开小说详情查看 人物/大纲/地图。")


if __name__ == "__main__":
    asyncio.run(main())